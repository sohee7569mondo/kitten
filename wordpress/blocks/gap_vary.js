    form:{ A:'기울기가 크지는 않아서 머리 쓰는 일도 잘 해내십니다. 다만 눈에 보이는 결과 하나를 가운데 두고 나머지를 붙이시면 훨씬 편합니다.',
           B:'기울기가 크지는 않아서 손으로 하는 일도 잘 해내십니다. 다만 뜻이나 이치를 다루는 일 하나를 가운데 두고 나머지를 붙이시면 훨씬 편합니다.' },
