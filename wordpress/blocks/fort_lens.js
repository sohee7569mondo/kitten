  function ord(){
    try{ return JSON.parse(localStorage.getItem('stella_demo')); }catch(e){ return null; }
  }
  function tail(){
    var o=ord();
    var t=String((o?o.topic:'')||'').trim();
    var p=t.split('·');
    return p[p.length-1].trim();
  }

  function setLens(){
    var o=ord();
    if(!o){ return; }
    if(o.guardian_slug!=='door-fortune'){ return; }
    var T=FORT[tail()];
    if(!T){ return; }
    var G=window.StellaGuide;
    if(!G){ return; }
    var g=G['door-fortune'];
    if(!g){ return; }
    g.lens = g.lens || {};
    var k;
    for(k in T){
      if(Object.prototype.hasOwnProperty.call(T,k)){ g.lens[k]=T[k]; }
    }
  }
  setLens();

  function heads(){
    var box=document.getElementById('ssb');
    if(!box){ return false; }
    var h3=box.getElementsByTagName('h3');
    if(!h3.length){ return false; }
    var i, key, t, hit=false;
    for(i=0;i<h3.length;i++){
      t=String(h3[i].textContent);
      if(t.indexOf('자리')<0){ continue; }
      if(t.indexOf('—')>=0){ continue; }
      for(key in EASY){
        if(!Object.prototype.hasOwnProperty.call(EASY,key)){ continue; }
        if(t.indexOf(key)!==0){ continue; }
        h3[i].innerHTML = EASY[key]+' <span style="font-weight:400;opacity:.72">— '+t+'</span>';
        hit=true;
      }
    }
    return hit;
  }

  var tries=0;
  function tick(){
    tries+=1;
    var done=false;
    try{ done=heads(); }catch(e){ done=true; }
    if(done){ return; }
    if(tries>60){ return; }
    setTimeout(tick, 400);
  }
  function go(){ setLens(); setTimeout(tick, 900); }
  if(document.readyState==='loading'){
    document.addEventListener('DOMContentLoaded', go);
  } else { go(); }
