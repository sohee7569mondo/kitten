/* ── 사람 한 명을 글로 ─────────────────────────────
   p 는 화면이 이미 쓰고 있는 자료 그대로입니다.
   p.gk '정화' · p.hi '토' · p.no ['목'] · p.sip ['정관','상관']
   ─────────────────────────────────────────────── */
function srRead( p, escFn ) {
  var esc = escFn ? escFn : function ( s ) { return String( s ); };
  var out = [];

  var gk  = p.gk ? String( p.gk ) : '';
  var hi  = p.hi ? String( p.hi ) : '';
  var no  = ( p.no ? p.no : [] );
  var sip = ( p.sip ? p.sip : [] );

  /* 한 줄 정의 */
  var tag = SR_TAG[ hi ];
  if ( tag ) {
    out.push( '<p class="sr-tag">' + esc( tag ) + '</p>' );
  }

  /* 어떤 사람인가 */
  var body = [];
  if ( SR_GAN_LINE[ gk ] ) { body.push( SR_GAN_LINE[ gk ] ); }
  if ( SR_HI_LINE[ hi ] )  { body.push( SR_HI_LINE[ hi ] ); }
  if ( body.length ) {
    out.push( '<h3>이 사람은 이런 사람입니다</h3>' );
    out.push( '<p>' + esc( body.join( ' ' ) ) + '</p>' );
  }

  /* 없는 것 */
  if ( no.length ) {
    var one = String( no[ 0 ] );
    var w   = ( no.length > 1 ) ? no.join( '도 ' ) : one;
    if ( SR_NO_LINE[ one ] ) {
      out.push( '<h3>없는 것</h3>' );
      out.push( '<p><b>여덟 글자 안에 ' + esc( w ) + '이 한 자도 없습니다.</b> ' +
                esc( SR_NO_LINE[ one ] ) + '</p>' );
    }
  }

  /* 세상을 대하는 법 */
  var s2 = [];
  var i;
  for ( i = 0; i < sip.length; i++ ) {
    var nm = String( sip[ i ] );
    if ( SR_SIP_LINE[ nm ] ) {
      s2.push( '<li><b>' + esc( nm ) + '</b> — ' + esc( SR_SIP_LINE[ nm ] ) + '</li>' );
    }
  }
  if ( s2.length ) {
    out.push( '<h3>세상을 대하는 법</h3>' );
    out.push( '<ul class="sr-sip">' + s2.join( '' ) + '</ul>' );
  }

  return out.join( '' );
}

/* ── 나와 이 사람 ──────────────────────────────────
   myGan  내 일간 한자 ('乙' 처럼)
   p      이 사람 자료
   sipFn  406 안에 이미 있는 sipsung(dayEl, dayYin, el, yin)
   ─────────────────────────────────────────────── */
function srMe( myGan, p, sipFn, escFn ) {
  var esc = escFn ? escFn : function ( s ) { return String( s ); };
  var me  = SR_GAN[ myGan ];
  var it  = SR_GAN[ p.g ];
  if ( ! me ) { return ''; }
  if ( ! it ) { return ''; }

  var rel = sipFn( me.el, me.yin, it.el, it.yin );
  var box = SR_REL[ rel ];
  if ( ! box ) { return ''; }

  var o = [];
  o.push( '<h3>나와 이 사람</h3>' );
  o.push( '<p class="sr-me-head">당신은 <b>' + esc( me.ko ) + '</b>입니다. ' +
          esc( p.n ) + '은(는) 당신에게 <b>' + esc( rel ) + '</b>입니다.</p>' );
  o.push( '<p class="sr-tag">' + esc( box.t ) + '</p>' );
  o.push( '<p>' + esc( box.p ) + '</p>' );
  return o.join( '' );
}
