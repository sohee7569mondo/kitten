  function esc(s){
    var AMP = String.fromCharCode(38);
    return String(s).replace(new RegExp(AMP, 'g'), AMP + 'amp;')
                    .replace(/</g, AMP + 'lt;').replace(/>/g, AMP + 'gt;');
  }
  /* 받침이 있으면 「은」, 없으면 「는」 */
  function eun(name){
    var c = String(name).charCodeAt(String(name).length - 1) - 0xAC00;
    if(c < 0){ return '은'; }
    if(c > 11171){ return '은'; }
    return (c % 28) ? '은' : '는';
  }

  /* 한 사람 쪽 — 그 사람이 나에게 무엇으로 오는가 */
  function side(godName, meName, youName){
    var s = SIP[godName];
    if(!s){ return ''; }
    var me = esc(meName), you = esc(youName);
    function fill(t){
      return String(t).replace(/\{그\}/g, you + '님').replace(/\{나\}/g, me);
    }
    var html = '<div class="sipbox">'
      + '<p class="sipname">' + esc(godName) + ' &middot; ' + s.title + '</p>'
      + '<p class="sipwho">' + me + '님이 보는 ' + you + '님</p>'
      + '<p>' + fill(s.lead) + '</p>'
      + '<p><b class="siptag">잘 되면</b> ' + fill(s.good) + '</p>'
      + '<p><b class="siptag no">걸리면</b> ' + fill(s.bad) + '</p>';
    if(s.end){ html += '<p class="sipend">' + fill(s.end) + '</p>'; }
    html += '</div>';
    return html;
  }

  /* 두 방향을 한 줄로 */
  function together(godAB, godBA, nameA, nameB){
    var a = SIP[godAB], b = SIP[godBA];
    if(!a){ return ''; }
    if(!b){ return ''; }
    var A = esc(nameA), B = esc(nameB);
    if(godAB === godBA){
      return '<p class="siptog">두 분이 서로에게 <em>같은 자리</em>입니다. '
           + A + '님도 ' + B + '님도 상대 앞에서 ' + b.clip[1] + '.</p>';
    }
    return '<p class="siptog">' + A + '님은 ' + B + '님 앞에서 ' + a.clip[0] + ', '
         + B + '님은 ' + A + '님 앞에서 ' + b.clip[1] + '.</p>';
  }

  /* 제 6 장 — 두 칸과 합치는 한 줄 */
  function chapter(ganA, ganB, nameA, nameB, tenGod){
    var godForA = tenGod(ganA, ganB);   /* A 가 보기에 B 는 무엇인가 */
    var godForB = tenGod(ganB, ganA);   /* B 가 보기에 A 는 무엇인가 */
    return {
      godForA: godForA,
      godForB: godForB,
      html: side(godForA, nameA, nameB)
          + side(godForB, nameB, nameA)
          + together(godForA, godForB, nameA, nameB)
    };
  }

  root.StellaMatchSip = { SIP: SIP, side: side, together: together, chapter: chapter };
