    var slots=[
      {k:'연간', el:GAN_EL[p.year.gan],  yin:GAN_YIN[p.year.gan],  han:p.year.han.charAt(0)},
      {k:'연지', el:JI_EL[p.year.ji],    yin:JI_YIN[p.year.ji],    han:p.year.han.charAt(1)},
      {k:'월간', el:GAN_EL[p.month.gan], yin:GAN_YIN[p.month.gan], han:p.month.han.charAt(0)},
      {k:'월지', el:JI_EL[p.month.ji],   yin:JI_YIN[p.month.ji],   han:p.month.han.charAt(1)},
      {k:'일지', el:JI_EL[p.day.ji],     yin:JI_YIN[p.day.ji],     han:p.day.han.charAt(1)}
    ];
    if(p.hour){
      slots.push({k:'시간', el:GAN_EL[p.hour.gan], yin:GAN_YIN[p.hour.gan], han:p.hour.han.charAt(0)});
      slots.push({k:'시지', el:JI_EL[p.hour.ji],   yin:JI_YIN[p.hour.ji],   han:p.hour.han.charAt(1)});
    }
    slots.forEach(function(s){ s.sip=sipsung(dayEl, dayYin, s.el, s.yin); });

    var count={}, gcount={};
    slots.forEach(function(s){
      count[s.sip]=(count[s.sip]||0)+1;
      var g=GROUP[s.sip];
      gcount[g]=(gcount[g]||0)+1;
    });

    /* 가장 두꺼운 십성 두 개 */
    var ranked=Object.keys(count).map(function(k){ return {sip:k, n:count[k]}; })
      .sort(function(a,b){ return b.n-a.n; });

    /* 축 계산 */
    var axis={};
    Object.keys(AXES).forEach(function(key){
      var A=AXES[key], sa=0, sb=0;
      A.a.forEach(function(s){ sa+=(count[s]||0); });
      A.b.forEach(function(s){ sb+=(count[s]||0); });
      var lean='';
      if(sa>sb) lean='A';
      if(sb>sa) lean='B';
      axis[key]={ a:sa, b:sb, lean:lean,
                  say: lean==='A' ? A.sayA : (lean==='B' ? A.sayB : '어느 쪽으로도 크게 기울지 않은 구조'),
                  name: lean==='A' ? A.A : (lean==='B' ? A.B : '가운데') };
    });

    var most=chart.five.slice().sort(function(a,b){ return b.count-a.count; })[0];
    var empty=chart.five.filter(function(f){ return f.count===0; });

    return {
      day: DAY[dayHan] || DAY['甲'],
      dayHan: dayHan,
      slots: slots,
      count: count,
      groups: gcount,
      top: ranked.slice(0,2),
      sipText: SIP,
      axis: axis,
      mostEl: most,
      mostElText: EL_MUCH[most.element],
      emptyEls: empty.map(function(e){ return e.element; }),
      emptyElText: empty.map(function(e){ return EL_NONE[e.element]; }),
      sun: SUN[chart.stars.sun.name] || '',
      asc: ASC[chart.stars.ascendant.name] || '',
      mc:  MC[chart.stars.midheaven.name] || ''
    };
