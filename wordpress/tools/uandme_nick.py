def check():
    bad = []
    for rel in RELS:
        rows = NICK.get(rel)
        if not rows or len(rows) != len(MINS):
            bad.append(rel + ' 칸 수가 열이 아닙니다')
            continue
        for i, (name, sub) in enumerate(rows):
            for t, txt, cap in (('이름', name, 16), ('훅', sub, 24)):
                if '&' in txt or "'" in txt or '"' in txt:
                    bad.append(rel + ' ' + str(i) + ' ' + t + ' 따옴표/앰퍼샌드')
                for ch in txt:
                    o = ord(ch)
                    ok = (0x20 <= o <= 0x7E) or (0xAC00 <= o <= 0xD7A3) or (0x3131 <= o <= 0x318E)
                    if not ok:
                        bad.append(rel + ' ' + str(i) + ' ' + t + ' 못 그릴 글자 ' + ch)
                if len(txt) > cap:
                    bad.append(rel + ' ' + str(i) + ' ' + t + ' 너무 김 ' + str(len(txt)) + ' ' + txt)
    for rel in RELS:
        rows = BODY.get(rel)
        if not rows or len(rows) != len(MINS):
            bad.append(rel + ' 본문 칸 수가 열이 아닙니다')
            continue
        for i, lines in enumerate(rows):
            if len(lines) != 3:
                bad.append(rel + ' ' + str(i) + ' 본문이 세 줄이 아닙니다')
            for txt in lines:
                if '&' in txt or "'" in txt or '"' in txt:
                    bad.append(rel + ' ' + str(i) + ' 본문 따옴표/앰퍼샌드')
                if len(txt) > 24:
                    bad.append(rel + ' ' + str(i) + ' 본문 너무 김 ' + txt)
                for ch in txt:
                    o = ord(ch)
                    ok = (0x20 <= o <= 0x7E) or (0xAC00 <= o <= 0xD7A3) or (0x3131 <= o <= 0x318E)
                    if not ok:
                        bad.append(rel + ' ' + str(i) + ' 본문 못 그릴 글자 ' + ch)
    if len(EMOJI) != len(MINS):
        bad.append('이모지가 열 개가 아닙니다')

